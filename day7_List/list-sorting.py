#Sort numbers ascending.
n = [33,22,44,245,5,66,43,3]
n.sort()
print(n)

#Sort numbers descending.
n.sort(reverse=True)
print(n)

#Reverse fruits list.
fruits = ['mango','banana','chikoo','pineapple']
fruits.reverse()
print(fruits)


#Reverse city list.
cities = ['mumbai','pune','bangalore']
cities.reverse()
print(cities)

#Sort marks.
marks = [55,77,66,56,77,87]
marks.sort()
print(marks)


#Sort salaries.
salary = [55555,77777,44444,33333]
salary.sort()
print(salary)


#Reverse numbers.
salary.reverse()

#Sort student names.
student_name = ['manish','dinesh','kiran']
